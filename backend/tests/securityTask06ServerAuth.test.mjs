let failures = 0
function assert(cond, msg) {
  if (cond) {
    console.log('PASS:', msg)
  } else {
    failures++
    console.error('FAIL:', msg)
  }
}

console.log('=== TASK 6: Server Authentication & JWT Protection Test Suite ===\n')

const testUser = {
  id: `usr_${uuidv4().slice(0, 8)}`,
  email: `test_auth_${uuidv4().slice(0, 8)}@example.com`,
  password: await bcrypt.hash('CorrectPass123!', 10),
  role: 'user',
}

await insert('users', {
  id: testUser.id,
  email: testUser.email,
  password: testUser.password,
  role: testUser.role,
})

// 1. JWT Algorithm Allowlist & Confusion Attack Prevention
console.log('--- 1. JWT Algorithm Allowlist (HS256 Only) ---')
{
  // 1.1 Valid HS256 token generated by server passes
  const validToken = generateAccessToken(testUser)
  const decoded = verifyAccessToken(validToken)
  assert(decoded.id === testUser.id, `valid HS256 token verifies successfully (got ${decoded.id})`)
  assert(decoded.role === testUser.role, `role preserved in token claims (got ${decoded.role})`)

  // 1.2 Alg: 'none' attack rejection
  const headerNone = Buffer.from(JSON.stringify({ alg: 'none', typ: 'JWT' })).toString('base64url')
  const payloadNone = Buffer.from(JSON.stringify({ id: testUser.id, email: testUser.email, role: 'admin' })).toString('base64url')
  const noneToken = `${headerNone}.${payloadNone}.`

  let threwOnNone = false
  try {
    verifyAccessToken(noneToken)
  } catch (err) {
    threwOnNone = true
  }
  assert(threwOnNone, 'token with alg: "none" is strictly rejected')

  // 1.3 Asymmetric / Unallowed algorithm rejection (e.g. HS384 / RS256 confusion)
  const hs384Token = jwt.sign(
    { id: testUser.id, role: 'admin' },
    config.jwtAccessSecret,
    { algorithm: 'HS384', expiresIn: '1h' }
  )
  let threwOnHs384 = false
  try {
    verifyAccessToken(hs384Token)
  } catch (err) {
    threwOnHs384 = true
  }
  assert(threwOnHs384, 'token with non-HS256 algorithm (HS384) is rejected by allowlist')

  // 1.4 Expired token rejection
  const expiredToken = jwt.sign(
    { id: testUser.id, role: testUser.role },
    config.jwtAccessSecret,
    { algorithm: 'HS256', expiresIn: -10 }
  )
  let threwOnExpired = false
  try {
    verifyAccessToken(expiredToken)
  } catch (err) {
    threwOnExpired = true
  }
  assert(threwOnExpired, 'expired token is rejected')

  // 1.5 Malformed token rejection
  let threwOnMalformed = false
  try {
    verifyAccessToken('malformed.token.string')
  } catch (err) {
    threwOnMalformed = true
  }
  assert(threwOnMalformed, 'malformed token is rejected')
}

// 2. Auth Middleware Claim Verification & Sanitization
console.log('\n--- 2. Auth Middleware Identity Extraction ---')
{
  const validToken = generateAccessToken(testUser)

  // 2.1 Standard valid Bearer header
  let req = { headers: { authorization: `Bearer ${validToken}` } }
  let res = {
    status(code) { this.statusCode = code; return this },
    json(body) { this.body = body; return this },
  }
  let nextCalled = false
  authMiddleware(req, res, () => { nextCalled = true })
  assert(nextCalled, 'valid token invokes next()')
  assert(req.user && req.user.id === testUser.id, 'req.user extracts strictly verified id from token')
  assert(req.user.role === 'user', 'req.user extracts role from verified claims')

  // 2.2 Missing token returns 401
  let unauthReq = { headers: {} }
  let unauthRes = {
    status(code) { this.statusCode = code; return this },
    json(body) { this.body = body; return this },
  }
  let unauthNext = false
  authMiddleware(unauthReq, unauthRes, () => { unauthNext = true })
  assert(!unauthNext && unauthRes.statusCode === 401, 'missing token returns 401')

  // 2.3 Invalid token returns 401
  let badReq = { headers: { authorization: 'Bearer bad.token.here' } }
  let badRes = {
    status(code) { this.statusCode = code; return this },
    json(body) { this.body = body; return this },
  }
  let badNext = false
  authMiddleware(badReq, badRes, () => { badNext = true })
  assert(!badNext && badRes.statusCode === 401, 'invalid token returns 401')

  // 2.4 optionalAuth with valid token sets req.user
  let optReq = { headers: { authorization: `Bearer ${validToken}` } }
  let optNext = false
  optionalAuth(optReq, {}, () => { optNext = true })
  assert(optNext && optReq.user && optReq.user.id === testUser.id, 'optionalAuth sets req.user for valid token')

  // 2.5 optionalAuth without token continues without error
  let optEmptyReq = { headers: {} }
  let optEmptyNext = false
  optionalAuth(optEmptyReq, {}, () => { optEmptyNext = true })
  assert(optEmptyNext && !optEmptyReq.user, 'optionalAuth continues without req.user when no token')

  // 2.6 Token with userId in payload (alternative claim)
  const altToken = jwt.sign(
    { userId: testUser.id, role: 'editor' },
    config.jwtAccessSecret,
    { algorithm: 'HS256', expiresIn: '1h' }
  )
  let altReq = { headers: { authorization: `Bearer ${altToken}` } }
  let altNext = false
  authMiddleware(altReq, {}, () => { altNext = true })
  assert(altNext && altReq.user && altReq.user.id === testUser.id, 'authMiddleware extracts userId claim')
}

// 3. Server-side Active User Check
